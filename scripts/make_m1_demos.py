"""M1 demos: fetch -> paint -> animate for the three demo inputs, with fixed seeds.

One command regenerates everything::

    python -m scripts.make_m1_demos [--insecure] [--only NAME] [--reuse] [--out outputs/m1]

For every ``configs/demos/m1_*.yaml``: verify/download the input (``scripts/fetch_demo_inputs``), run the
optimization baseline (``paint_optim`` with the demo's seed and bitwise-reproducible cuDNN), save the
``StrokeSequence``, compute the final-image metrics, render the stroke-by-stroke animation and export
MP4 + GIF. Outputs: ``<out>/<name>/`` (sequence, PNGs, metrics.json, MP4, GIF) and, committed,
``docs/media/m1_<name>.gif``, ``docs/media/m1_<name>_compare.jpg`` and ``docs/media/m1_results.md``
(generated from the metrics JSONs). ``--reuse`` skips painting when a sequence already exists (animation
tuning only).
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import sys
from dataclasses import dataclass, field
from pathlib import Path

import torch
from PIL import Image

from brushstroke.animation import AnimationConfig, FrameRenderer, export_frames
from brushstroke.animation.frames import output_size
from brushstroke.baselines.optim.config import PaintOptimConfig
from brushstroke.baselines.optim.optimize import paint_optim
from brushstroke.eval.metrics import image_metrics
from brushstroke.strokes import StrokeSequence
from brushstroke.utils.config import dump_config, load_config
from brushstroke.utils.device import get_device
from brushstroke.utils.io import center_crop_resize, load_image, save_image
from brushstroke.utils.seed import seed_everything
from scripts.fetch_demo_inputs import DEMO_DIR, fetch_demo_inputs

MEDIA = Path("docs/media")
MAX_GIF_BYTES = 4 * 1024 * 1024
TARGETS = {
    "lpips_vgg": 0.35,
    "lpips_alex": 0.40,
}  # revised M1 target (docs/experiments/optim_sweep.md)


@dataclass
class DemoConfig:
    """One demo: input image, painting settings and animation settings (defaults = baselines)."""

    name: str = ""
    image_id: str = ""
    paint: PaintOptimConfig = field(default_factory=PaintOptimConfig)
    animation: AnimationConfig = field(default_factory=AnimationConfig)


def sequence_sha256(seq: StrokeSequence) -> str:
    """Hash of what defines the painting (parameters, brush variants, canvas size, tags), not of timings."""
    h = hashlib.sha256()
    assert seq.brush_index is not None and seq.scale_level is not None and seq.patch_id is not None
    for t in (seq.params, seq.brush_index, seq.scale_level, seq.patch_id):
        h.update(t.cpu().numpy().tobytes())
    h.update(json.dumps(seq.canvas_size).encode())
    return h.hexdigest()


def paint_demo(
    cfg: DemoConfig, image_path: Path, out: Path
) -> tuple[StrokeSequence, torch.Tensor, dict[str, float]]:
    """Paint one demo; returns the sequence, the target and the metrics (also written to ``out``)."""
    p = cfg.paint
    seed_everything(p.seed, p.deterministic, p.cudnn_deterministic)
    device = get_device(p.device)
    size = (p.optim.height, p.optim.width)
    target = center_crop_resize(load_image(image_path), size)
    save_image(target, out / "target.png")
    seq = paint_optim(target, p.optim, p.loss, p.brush, p.render, p.seed, device)
    seq.save(out / "sequence.npz")
    final = seq.render(cfg=p.render).to(device)
    save_image(final, out / "final.png")
    metrics = image_metrics(final, target.to(device))
    metrics |= {
        "num_strokes": float(len(seq)),
        "runtime_seconds": float(seq.meta["runtime_seconds"]),
        "peak_vram_mb": float(seq.meta["peak_vram_mb"]),
    }
    return seq, target, metrics


def compare_image(target_png: Path, final_png: Path, dest: Path, side: int = 384) -> None:
    """Side-by-side target | painting (JPEG, small)."""
    a, b = (
        Image.open(p).convert("RGB").resize((side, side), Image.LANCZOS)
        for p in (target_png, final_png)
    )
    sheet = Image.new("RGB", (2 * side + 8, side), (255, 255, 255))
    sheet.paste(a, (0, 0))
    sheet.paste(b, (side + 8, 0))
    dest.parent.mkdir(parents=True, exist_ok=True)
    sheet.save(dest, quality=88)


def animate_demo(cfg: DemoConfig, seq: StrokeSequence, out: Path) -> dict[str, Path]:
    renderer = FrameRenderer(seq, cfg.animation)
    h, w = output_size(seq, cfg.animation)
    return export_frames(renderer.frames(), out / cfg.name, (w, h), cfg.animation)


def results_markdown(rows: list[dict[str, object]]) -> str:
    """The metrics table of ``docs/media/m1_results.md`` (generated from the metrics JSONs)."""
    lines = [
        "# M1 demos: results",
        "",
        "Generated by `python -m scripts.make_m1_demos` from `outputs/m1/<name>/metrics.json` (do not edit by hand).",
        f"Revised M1 target (docs/experiments/optim_sweep.md): LPIPS-VGG <= {TARGETS['lpips_vgg']}, held-out LPIPS-Alex <= "
        f"{TARGETS['lpips_alex']}, <= 2000 strokes, <= 10 min per 512 px image.",
        "",
        "| demo | input | strokes | L1 | PSNR (dB) | SSIM | LPIPS-VGG | LPIPS-Alex | runtime (min) | peak VRAM (GB) | seed | GIF (MB) | sequence sha256 | target met |",
        "|------|-------|---------|----|-----------|------|-----------|------------|-------------|----------------|------|----------|-----------------|------------|",
    ]
    for r in rows:
        m: dict[str, float] = r["metrics"]  # type: ignore[assignment]
        met = (
            m["lpips_vgg"] <= TARGETS["lpips_vgg"]
            and m["lpips_alex"] <= TARGETS["lpips_alex"]
            and m["num_strokes"] <= 2000 + 50
        )
        lines.append(
            f"| {r['name']} | {r['image_id']} | {m['num_strokes']:.0f} | {m['l1']:.4f} | {m['psnr']:.2f} | {m['ssim']:.3f} | "
            f"{m['lpips_vgg']:.3f} | {m['lpips_alex']:.3f} | {m['runtime_seconds'] / 60:.1f} | {m['peak_vram_mb'] / 1024:.1f} | "
            f"{r['seed']} | {r['gif_mb']:.2f} | `{str(r['sequence_sha256'])[:12]}` | {'yes' if met else 'NO'} |"
        )
    lines += [
        "",
        "Notes: every demo is the baseline defaults (`configs/baseline_optim.yaml`) with seed 0 and `cudnn_deterministic: true`, so the whole run is "
        "bitwise reproducible on the GPU: the sequence hash (parameters, brush variants, tags) is identical across reruns. "
        "A demo marked NO misses the revised target; textured, high-frequency inputs (see `docs/experiments/optim_sweep.md`, per-image table) "
        "are expected to. GIFs: 480 px, 15 fps, 10 s of painting + 2 s hold, coarse-to-fine pacing (`easing: by_level`).",
        "",
        "Side-by-side (input | painting): "
        + ", ".join(
            f"[{r['name']}](m1_{str(r['name']).removeprefix('m1_')}_compare.jpg)" for r in rows
        ),
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> list[dict[str, object]]:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawTextHelpFormatter
    )
    parser.add_argument("--out", type=Path, default=Path("outputs/m1"))
    parser.add_argument(
        "--media", type=Path, default=MEDIA, help="where the GIFs/compare images/results.md go"
    )
    parser.add_argument(
        "--results-only",
        action="store_true",
        help="only rewrite m1_results.md from the stored metrics JSONs",
    )
    parser.add_argument("--only", action="append", help="demo name (repeatable)")
    parser.add_argument(
        "--reuse", action="store_true", help="reuse an existing sequence.npz (skip painting)"
    )
    parser.add_argument(
        "--insecure", action="store_true", help="skip TLS verification when downloading"
    )
    args = parser.parse_args(argv)

    if args.results_only:
        rows = [
            json.loads(p.read_text(encoding="utf-8"))
            for p in sorted(args.out.glob("m1_*/metrics.json"))
        ]
        args.media.mkdir(parents=True, exist_ok=True)
        (args.media / "m1_results.md").write_text(results_markdown(rows), encoding="utf-8")
        print(f"wrote {args.media / 'm1_results.md'} from {len(rows)} metrics files")
        return rows
    paths = fetch_demo_inputs(args.insecure)
    rows: list[dict[str, object]] = []
    for cfg_path in sorted(DEMO_DIR.glob("m1_*.yaml")):
        cfg = load_config(DemoConfig, cfg_path)
        if args.only and cfg.name not in args.only:
            continue
        out = args.out / cfg.name
        out.mkdir(parents=True, exist_ok=True)
        dump_config(cfg, out)
        seq_path = out / "sequence.npz"
        if args.reuse and seq_path.exists():
            seq = StrokeSequence.load(seq_path)
            metrics = json.loads((out / "metrics.json").read_text(encoding="utf-8"))["metrics"]
        else:
            print(f"== {cfg.name}: painting {cfg.image_id}", flush=True)
            seq, _, metrics = paint_demo(cfg, paths[cfg.image_id], out)
        print(f"== {cfg.name}: animating {len(seq)} strokes", flush=True)
        files = animate_demo(cfg, seq, out)
        gif = args.media / f"{cfg.name}.gif"
        gif_size = files["gif"].stat().st_size
        if gif_size > MAX_GIF_BYTES:
            raise RuntimeError(
                f"{cfg.name}: GIF is {gif_size / 1e6:.2f} MB > 4 MB; lower gif_width/gif_fps"
            )
        args.media.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(files["gif"], gif)
        compare_image(out / "target.png", out / "final.png", args.media / f"{cfg.name}_compare.jpg")
        row: dict[str, object] = {
            "name": cfg.name,
            "image_id": cfg.image_id,
            "seed": cfg.paint.seed,
            "metrics": metrics,
            "sequence_sha256": sequence_sha256(seq),
            "gif_mb": gif_size / 1e6,
            "files": {k: str(v) for k, v in files.items()},
        }
        (out / "metrics.json").write_text(json.dumps(row, indent=2), encoding="utf-8")
        rows.append(row)
        print(
            json.dumps(
                {k: row[k] for k in ("name", "metrics", "sequence_sha256", "gif_mb")}, indent=2
            ),
            flush=True,
        )
    if rows and not args.only:
        (args.media / "m1_results.md").write_text(results_markdown(rows), encoding="utf-8")
        print(f"wrote {args.media / 'm1_results.md'}")
    return rows


if __name__ == "__main__":
    main(sys.argv[1:])
